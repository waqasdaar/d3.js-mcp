import { writeFileSync } from "node:fs";
import path from "node:path";
import { computeCapabilities, STATUSES, type CapabilityReport } from "../src/core/capabilities/registry.js";
import { listRenderers } from "../src/renderers/registry.js";
import { PACKAGE_ROOT } from "../src/shared/config.js";

const SOURCE_BASE = "https://github.com/d3/d3/tree/main/docs";

export async function writeCoverageReport(): Promise<CapabilityReport> {
  const r = computeCapabilities();
  writeFileSync(
    path.join(PACKAGE_ROOT, "data", "d3-api-coverage.json"),
    JSON.stringify(
      {
        ...r,
        entries: r.entries.map(({ id, module, normalized, kind, status, usedBy, docUrl }) => ({
          id,
          module,
          normalized,
          kind,
          status,
          usedBy,
          docUrl,
        })),
      },
      null,
      2,
    ) + "\n",
  );
  const pct = (n: number) => `${((n / r.totals.total) * 100).toFixed(1)}%`;
  const lines: string[] = [];
  lines.push("# D3 API coverage report", "");
  lines.push("> Generated by `npm run audit:d3` from the official API index. Do not edit by hand.", "");
  lines.push(`- **Source:** ${r.source}`);
  lines.push(`- **Retrieved:** ${r.retrievedAt}`);
  lines.push(`- **Installed d3 version:** ${r.d3Version}`);
  lines.push(`- **Counting method:** ${r.countingMethod}`, "");
  lines.push("## Status definitions", "");
  for (const s of STATUSES) lines.push(`- \`${s}\`: ${r.statusRules[s]}`);
  lines.push("", "## Totals", "", "| Status | Entries | Share |", "|---|---:|---:|");
  for (const s of STATUSES) lines.push(`| \`${s}\` | ${r.totals[s]} | ${pct(r.totals[s])} |`);
  lines.push(`| **total** | **${r.totals.total}** | 100% |`, "");
  const used =
    r.totals["implemented-and-tested"] +
    r.totals["implemented-with-constraints"] +
    r.totals["available-through-safe-composition"];
  lines.push(
    `Entries reachable through renderers, the browser runtime, or safe composition: **${used} / ${r.totals.total} (${pct(used)})**. The rest are documented but not yet exposed. This report does **not** claim complete D3 coverage.`,
    "",
  );
  lines.push(
    "## Per module",
    "",
    `| Module | Total | ${STATUSES.map((s) => s.replace(/-/g, " ")).join(" | ")} | Docs | Source |`,
    `|---|---:|${STATUSES.map(() => "---:").join("|")}|---|---|`,
  );
  for (const m of r.modules) {
    lines.push(
      `| ${m.module} | ${m.total} | ${STATUSES.map((s) => m[s]).join(" | ")} | [docs](https://d3js.org/${m.module}) | [source](https://github.com/d3/${m.module}) |`,
    );
  }
  lines.push(
    "",
    "## Visualization renderers",
    "",
    "| Type | Family | Core D3 | Description |",
    "|---|---|---|---|",
  );
  for (const p of listRenderers())
    lines.push(`| \`${p.type}\` | ${p.family} | ${p.core ? "yes" : "no (plugin)"} | ${p.description} |`);
  lines.push("", "## Runtime export cross-check", "");
  lines.push(
    `- Exports present in the installed \`d3\` package but not listed in the index: ${r.runtimeExportsNotInIndex.length ? r.runtimeExportsNotInIndex.map((x) => `\`${x}\``).join(", ") : "none"}`,
  );
  lines.push(
    `- Index entries (exports/constructors) not found as top-level runtime exports: ${r.indexExportsMissingAtRuntime.length ? r.indexExportsMissingAtRuntime.map((x) => `\`${x}\``).join(", ") : "none"}`,
  );
  lines.push(
    `- Usage keys declared by renderers/composition that do not match an index entry: ${r.unmatchedUsageKeys.length ? r.unmatchedUsageKeys.map((x) => `\`${x}\``).join(", ") : "none"}`,
  );
  lines.push("", "## Full entry list", "");
  for (const m of r.modules) {
    lines.push(`### ${m.module}`, "", "| API | Kind | Status | Used by |", "|---|---|---|---|");
    for (const e of r.entries.filter((x) => x.module === m.module)) {
      lines.push(
        `| [${e.symbol.replace(/\|/g, "\\|")}](${e.docUrl}) | ${e.kind} | ${e.status} | ${e.usedBy.slice(0, 4).join(", ")}${e.usedBy.length > 4 ? ` +${e.usedBy.length - 4}` : ""} |`,
      );
    }
    lines.push("");
  }
  lines.push(`Documentation source tree: ${SOURCE_BASE}`, "");
  writeFileSync(path.join(PACKAGE_ROOT, "docs", "d3-api-coverage.md"), lines.join("\n"));
  return r;
}
